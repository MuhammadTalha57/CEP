"""Stage 7: Kaggle (development) vs AWS (cloud-hosted) comparison on paired trials.

  python scripts/cloud_compare.py            # writes reports/cloud_aws.md and paper/cloud_table.tex

Pairs every valid AWS trial with the Kaggle trial of the same model, app, defense and trial id
(same payload and seed). Reports per group: success agreement (exact McNemar), identical outputs,
and median latency inside the server and at the harness. Invalid trials (e.g. the 15-16 Nov
connection outage) are left out; the report keeps the last record per trial.
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from llmsec.harness.report import load  # noqa: E402
from llmsec.harness.stats import mcnemar_exact, percentile  # noqa: E402


def groups():
    recs = [r for r in load([ROOT / "results" / "kaggle", ROOT / "results" / "aws"]) if r["eval"]["valid"]]
    kag = {(r["model"], r["app"], r["defense"], r["trial_id"]): r for r in recs if r["env"] == "kaggle"}
    g = defaultdict(list)
    for r in recs:
        if r["env"] == "aws":
            k = (r["model"], r["app"], r["defense"], r["trial_id"])
            if k in kag:
                g[(r["model"], r["app"], r["defense"])].append((kag[k], r))
    return g


def summarize(pairs):
    att = [(a, b) for a, b in pairs if a["kind"] == "attack"]
    cln = [(a, b) for a, b in pairs if a["kind"] == "clean"]
    only_k = sum(1 for a, b in pairs if a["eval"]["success"] and not b["eval"]["success"])
    only_a = sum(1 for a, b in pairs if b["eval"]["success"] and not a["eval"]["success"])
    srv = lambda r: r["response"].get("server_ms", r["wall_ms"]) / 1000
    return {
        "n": len(pairs), "n_att": len(att), "n_cln": len(cln),
        "asr_k": sum(a["eval"]["success"] for a, _ in att), "asr_a": sum(b["eval"]["success"] for _, b in att),
        "util_k": sum(a["eval"]["success"] for a, _ in cln), "util_a": sum(b["eval"]["success"] for _, b in cln),
        "agree": len(pairs) - only_k - only_a, "only_k": only_k, "only_a": only_a,
        "p": mcnemar_exact(only_k, only_a),
        "same_out": sum(a["response"].get("output", "") == b["response"].get("output", "") for a, b in pairs),
        "srv_k": percentile([srv(a) for a, _ in pairs], 0.5), "srv_a": percentile([srv(b) for _, b in pairs], 0.5),
        "wall_a": percentile([b["wall_ms"] / 1000 for _, b in pairs], 0.5),
    }


def pct(k, n):
    return f"{100 * k / n:.1f}" if n else "–"


def main():
    g = groups()
    rows = [(key, summarize(p)) for key, p in sorted(g.items())]
    tot = summarize([x for p in g.values() for x in p])
    md = ["# Kaggle vs AWS (cloud-hosted) on paired trials", "",
          "Generated by `scripts/cloud_compare.py` from `results/kaggle` and `results/aws` (valid trials only).",
          "Kaggle: in-process, 2x T4 GPU. AWS: EC2 m7i-flex.large (2 vCPU, no GPU, ap-southeast-2), Docker, HTTP,",
          "attacked from a laptop. Same Ollama 0.40.16, same model digests, same trial ids, seeds and payloads.", "",
          "| model | app | defense | paired n | ASR Kaggle | ASR AWS | utility Kaggle | utility AWS | same outcome | McNemar p | identical output | median server s Kaggle | median server s AWS | median wall s AWS |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for (m, app, d), s in rows:
        md.append(f"| {m} | {app} | {d} | {s['n']} | {s['asr_k']}/{s['n_att']} | {s['asr_a']}/{s['n_att']} | "
                  f"{s['util_k']}/{s['n_cln']} | {s['util_a']}/{s['n_cln']} | {s['agree']}/{s['n']} | {s['p']:.2g} | "
                  f"{s['same_out']}/{s['n']} | {s['srv_k']:.2f} | {s['srv_a']:.2f} | {s['wall_a']:.2f} |")
    md += ["", f"**Total:** {tot['n']} paired trials; same success outcome in {tot['agree']}/{tot['n']} "
               f"({pct(tot['agree'], tot['n'])}%; {tot['only_k']} succeeded only on Kaggle, {tot['only_a']} only on AWS, "
               f"exact McNemar p = {tot['p']:.2g}); identical output text in {tot['same_out']}/{tot['n']} "
               f"({pct(tot['same_out'], tot['n'])}%)."]
    (ROOT / "reports" / "cloud_aws.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    tex = [r"\begin{table*}[t]",
           r"\caption{Development (Kaggle, GPU, in process) vs cloud-hosted deployment (AWS EC2, CPU, Docker, HTTP) on paired trials "
           r"(same model, defense, payload and seed). ASR and utility as successes/trials; latency = median seconds per trial.}",
           r"\label{tab:cloud}", r"\centering\scriptsize\setlength{\tabcolsep}{3.5pt}",
           r"\begin{tabular}{@{}lllrcccccrrrr@{}}", r"\toprule",
           r"Model & App & Defense & $n$ & ASR K & ASR A & Util.\ K & Util.\ A & Same outcome & McNemar $p$ & Identical out. & Server K & Server A / wall A \\",
           r"\midrule"]
    for (m, app, d), s in rows:
        tex.append(f"{m} & {app} & {d} & {s['n']} & {s['asr_k']}/{s['n_att']} & {s['asr_a']}/{s['n_att']} & "
                   f"{s['util_k']}/{s['n_cln']} & {s['util_a']}/{s['n_cln']} & {s['agree']}/{s['n']} & {s['p']:.2g} & "
                   f"{s['same_out']}/{s['n']} & {s['srv_k']:.2f} & {s['srv_a']:.2f} / {s['wall_a']:.2f} \\\\")
    tex += [r"\midrule",
            f"Total & & & {tot['n']} & & & & & {tot['agree']}/{tot['n']} & {tot['p']:.2g} & {tot['same_out']}/{tot['n']} & & \\\\",
            r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    (ROOT / "paper" / "cloud_table.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
